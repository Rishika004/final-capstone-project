def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", default=LT)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()

    trials = json.load(open(os.path.join(a.dir, "trials.json"), encoding="utf-8"))
    man = json.load(open(os.path.join(a.dir, "manifest.json"), encoding="utf-8"))
    stim_dir = os.path.join(a.dir, "stimuli")

    named = set()
    for t in trials:
        for k in ("ref", "test"):
            p = os.path.join(a.dir, t[k].replace("/", os.sep))
            if not os.path.isfile(p):
                raise SystemExit(f"[page] trial {t['trial_id']} names a missing file: {t[k]}")
            named.add(os.path.basename(t[k]))
    on_disk = {f for f in os.listdir(stim_dir) if f.endswith(".wav")}
    extra = sorted(on_disk - named)
    if extra:
        raise SystemExit(f"[page] {len(extra)} wavs on disk are in no trial, first {extra[0]}; "
                         f"rebuild stimuli and page together")
    if "condition" in json.dumps(trials):
        raise SystemExit("[page] trials.json carries a condition field; the page must be blind")

    n_main = sum(t["block"] == "main" for t in trials)
    print(f"[page] {len(trials)} trials ({n_main} main, {len(trials) - n_main} anchor repeats), "
          f"{len(named)} distinct stimuli")
    if a.check:
        print("[page] --check: nothing written")
        return
    html = PAGE % dict(seed=man.get("seed", ""), n_trials=len(trials),
                       lufs=man.get("target_lufs", float("nan")),
                       trials=json.dumps(trials, separators=(",", ":")),
                       build=json.dumps(dict(seed=man.get("seed", "")), separators=(",", ":")))
    out = os.path.join(a.dir, "index.html")
    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(html)
    print(f"[page] wrote {out} ({len(html) / 1024:.1f} KB); the condition name appears nowhere in it")


if __name__ == "__main__":
    main()
