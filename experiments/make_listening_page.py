"""
experiments/make_listening_page.py
==================================
Generate `listening_test/index.html` FROM the stimuli that actually exist.

WHY THIS IS A SCRIPT AND NOT AN EDIT
------------------------------------
`make_listening_stimuli.py` rebuilt the stimuli for the shipping arm on
2026-10-05 (48 files, 8 speakers x 6 conditions, -23 LUFS, blinded filenames,
key in `stimuli_key.csv`). The page was left pointing at the OLD `audio/`
directory: six different speakers, the stale non-segment arms
(`mcadams_*`, `tilt`, `additive_*`), unnormalised loudness, and the condition
name visible in every filename.

So a listener opening the page would have rated exactly the stimuli council #6
rejected, while the correct stimuli sat unused next to them. That is the §25 /
§37e failure mode again -- two artefacts that have to agree, kept in step by
hand. Generating the page from the key makes disagreement impossible: the
trials are whatever the key says, or the script fails.

THE DESIGN, UNCHANGED FROM THE 2026-09-16 PAGE
----------------------------------------------
Part 1, naturalness: every stimulus once, "How natural does this sound as
  speech?", 1-5. 48 trials.
Part 2, identity: every non-original condition against that speaker's own clean
  original as the reference, "How confident are you that these are the same
  speaker?", 1-5. 40 trials.

Both parts are shuffled per listener from a seed derived from the listener id,
so order effects do not align across people.

WHAT IS NEW
-----------
* **Blind throughout.** Trials carry `stim_id` only. The condition never
  appears in the DOM, the filename or the exported CSV. Unblinding happens at
  analysis time by joining `stim_id` against `stimuli_key.csv`, which is also
  why that join column is now exported.
* **The screener is computed, not eyeballed.** The manifest fixes the two
  anchor criteria (`original` rated >= 4, `anchor_noise` <= 2). The page
  evaluates them from the listener's own ratings and writes `screen_pass`,
  `anchor_hi_mean` and `anchor_lo_mean` into the export. The listener is told
  nothing about it -- being told would defeat it -- and nothing is rejected in
  the browser; exclusion is a decision made in the analysis, on the record.
* **The export can leave the browser.** The old page offered a file download
  only, which is awkward on a crowdsourcing platform. The CSV is now also shown
  in a selectable box with a copy button, so a participant can paste it into a
  completion field.

Run:
  python experiments/make_listening_page.py
  python experiments/make_listening_page.py --check     # verify only
"""
