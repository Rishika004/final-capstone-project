def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--stimuli-dir", default=os.path.join(LT, "stimuli"),
                    dest="stimuli_dir")
    ap.add_argument("--key", default=os.path.join(LT, "stimuli_key.csv"))
    ap.add_argument("--manifest", default=os.path.join(LT,
                                                       "stimuli_manifest.json"))
    ap.add_argument("--out", default=os.path.join(LT, "index.html"))
    ap.add_argument("--check", action="store_true",
                    help="validate the key against the files on disk and print "
                         "the trial counts, without writing the page")
    a = ap.parse_args()

    import pandas as pd

    key = pd.read_csv(a.key)
    man = json.load(open(a.manifest, encoding="utf-8"))

    # Every stimulus the key names must exist, and nothing may be served that
    # the key does not name. A page that silently drops a condition would
    # unbalance the design without saying so.
    key["file"] = "stimuli/stim_" + key.stim_id.astype(str) + ".wav"
    missing = [f for f in key.file
               if not os.path.isfile(os.path.join(LT, f.replace("/", os.sep)))]
    if missing:
        raise SystemExit(f"[page] {len(missing)} stimuli in the key are not on "
                         f"disk, first: {missing[0]}")
    on_disk = {f for f in os.listdir(a.stimuli_dir) if f.endswith(".wav")}
    named = {os.path.basename(f) for f in key.file}
    extra = sorted(on_disk - named)
    if extra:
        raise SystemExit(f"[page] {len(extra)} wavs in {a.stimuli_dir} are not "
                         f"in the key, first: {extra[0]}. Regenerate the "
                         f"stimuli and the key together.")

    conds = [c["name"] for c in man["conditions"]]
    if "original" not in conds:
        raise SystemExit("[page] no 'original' condition: part 2 has no reference")
    # Each speaker must have exactly one stimulus per condition.
    piv = key.pivot_table(index="speaker", columns="condition",
                          values="stim_id", aggfunc="count").fillna(0)
    bad = piv[(piv != 1).any(axis=1)]
    if len(bad):
        raise SystemExit(f"[page] unbalanced design for speakers "
                         f"{list(bad.index)}:\n{bad.to_string()}")

    trials_a, trials_b = [], []
    orig = (key[key.condition == "original"]
            .set_index("speaker")["file"].to_dict())
    for _, r in key.iterrows():
        trials_a.append(dict(block="A", stim_id=r.stim_id, file=r.file))
        if r.condition != "original":
            trials_b.append(dict(block="B", stim_id=r.stim_id, file=r.file,
                                 ref=orig[r.speaker]))

    # The anchors, by stim_id, so the screener never needs the condition name.
    hi = sorted(key[key.condition == "original"].stim_id.astype(str))
    lo = sorted(key[key.condition == "anchor_noise"].stim_id.astype(str))
    if not hi or not lo:
        raise SystemExit("[page] need both anchor conditions for the screener")
    screen = dict(hi=hi, lo=lo, hi_min=4, lo_max=2)

    print(f"[page] {len(key)} stimuli | {key.speaker.nunique()} speakers x "
          f"{key.condition.nunique()} conditions")
    print(f"[page] part 1 (naturalness): {len(trials_a)} trials")
    print(f"[page] part 2 (identity):    {len(trials_b)} trials")
    print(f"[page] screener: {len(hi)} high anchors (>= {screen['hi_min']}), "
          f"{len(lo)} low anchors (<= {screen['lo_max']})")
    print(f"[page] conditions: {', '.join(sorted(key.condition.unique()))}")
    if a.check:
        print("[page] --check: nothing written")
        return

    html = PAGE % dict(
        seed=man.get("seed", ""), lufs=man.get("target_lufs", float("nan")),
        n_stim=len(key),
        trials_a=json.dumps(trials_a, separators=(",", ":")),
        trials_b=json.dumps(trials_b, separators=(",", ":")),
        screen=json.dumps(screen, separators=(",", ":")),
        build=json.dumps(dict(seed=man.get("seed", ""),
                              target_lufs=man.get("target_lufs", None)),
                         separators=(",", ":")))
    with open(a.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(html)
    print(f"[page] wrote {a.out} ({len(html) / 1024:.1f} KB)")
    print("[page] the condition name appears nowhere in the page; unblind at "
          "analysis time by joining stim_id against stimuli_key.csv")


if __name__ == "__main__":
    main()
